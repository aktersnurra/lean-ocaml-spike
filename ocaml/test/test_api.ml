(* Tests for the generated client (wire format v2): ocaml/api/spike_api.ml, generated by
   #gen_ocaml from the Lean types in domain/Spike/Api.lean.
   The generated OCaml codecs are unverified, so they are checked against the Lean codecs:
   - echo: OCaml encodes, Lean decodes and re-encodes, OCaml decodes; must be the identity;
   - decoder agreement: on random bytes, Spike_api.decode_request and the Lean core must
     agree on accept/reject (and on the error), and every reply must decode;
   - semantics: priced quotes agree with the v1 native oracle. *)

open Spike_api

let failures = ref 0
let fail fmt = Printf.ksprintf (fun s -> incr failures; print_endline ("FAIL " ^ s)) fmt
let z = Z.of_int
let hex b = String.concat " " (List.map (fun c -> Printf.sprintf "%02x" (Char.code c)) (List.of_seq (Bytes.to_seq b)))

let pp_err = function Empty -> "Empty" | NotBytes -> "NotBytes" | UnknownOp -> "UnknownOp" | Truncated -> "Truncated" | Trailing -> "Trailing" | BadTag -> "BadTag"
let pp_oe = function NoLines -> "NoLines" | ZeroQty -> "ZeroQty" | BadDiscount -> "BadDiscount" | DuplicateSku -> "DuplicateSku"
let pp = function
  | Ok (Response_gate1 n) -> "gate1 " ^ Z.to_string n
  | Ok (Quote q) -> Printf.sprintf "quote %s/%s/%s/%s" (Z.to_string q.subtotal) (Z.to_string q.discount) (Z.to_string q.total) (Z.to_string q.line_count)
  | Ok (Echoed o) -> Printf.sprintf "echoed (%d lines)" (List.length o.lines)
  | Error (Transport e) -> "transport " ^ pp_err e
  | Error (Order e) -> "order " ^ pp_oe e

let expect name got want = if got = want then Printf.printf "ok   %-34s %s\n" name (pp got) else fail "%s: got %s, want %s" name (pp got) (pp want)
let line s q p = { sku = z s; qty = z q; unit_price = z p }
let order ?(customer = 1) pct lines = { customer = z customer; discount_pct = z pct; lines }

let () =
  print_endline "-- typed calls (every constructor of Request, Response and ApiError)";
  expect "gate1" (call (Request_gate1 (z 21))) (Ok (Response_gate1 (z 43)));
  let big = Z.shift_left Z.one 100 in
  expect "gate1 2^100" (call (Request_gate1 big)) (Ok (Response_gate1 (Z.succ (Z.mul big (z 2)))));
  expect "priceOrder ok" (call (PriceOrder (order 10 [ line 7 2 150; line 8 1 100 ])))
    (Ok (Quote { subtotal = z 400; discount = z 40; total = z 360; line_count = z 2 }));
  expect "priceOrder noLines" (call (PriceOrder (order 0 []))) (Error (Order NoLines));
  expect "priceOrder zeroQty" (call (PriceOrder (order 0 [ line 1 0 5 ]))) (Error (Order ZeroQty));
  expect "priceOrder badDiscount" (call (PriceOrder (order 101 [ line 1 1 5 ]))) (Error (Order BadDiscount));
  expect "priceOrder duplicateSku" (call (PriceOrder (order 0 [ line 1 1 5; line 1 2 5 ]))) (Error (Order DuplicateSku));
  let o = order ~customer:99 50 [ line 1 2 3; { sku = z 4; qty = z 5; unit_price = big } ] in
  expect "echo" (call (Echo o)) (Ok (Echoed o));
  print_endline "-- transport errors (raw bytes into Leancore.call_api, reply decoded by the generated client)";
  let raw name bs want =
    let reply = Leancore.call_api (Bytes.of_string bs) in
    match decode_reply reply with
    | Ok got -> expect name got want
    | Error c -> fail "%s: reply does not decode (code %d): %s" name c (hex reply)
  in
  raw "empty request" "" (Error (Transport Truncated));
  raw "unknown request tag" "\x09" (Error (Transport BadTag));
  raw "truncated varint" "\x00\x80" (Error (Transport Truncated));
  raw "trailing bytes" "\x00\x05\x00" (Error (Transport Trailing));

  print_endline "-- echo round trips (OCaml enc -> Lean dec/enc -> OCaml dec)";
  Random.init 11;
  let rz () = match Random.int 5 with 0 -> z 0 | 1 -> z (Random.int 128) | 2 -> z (Random.bits ()) | 3 -> Z.shift_left (z (Random.bits ())) (Random.int 200) | _ -> z (Random.int 100_000) in
  let ro () = { customer = rz (); discount_pct = rz (); lines = List.init (Random.int 20) (fun _ -> { sku = rz (); qty = rz (); unit_price = rz () }) } in
  let n_echo = 20_000 and bad = ref 0 in
  for _ = 1 to n_echo do
    let o = ro () in
    match call (Echo o) with
    | Ok (Echoed o') when o' = o -> ()
    | r -> incr bad; if !bad < 5 then fail "echo mismatch: %s" (pp r)
  done;
  Printf.printf "echo: %d random orders, %d mismatches\n" n_echo !bad;

  print_endline "-- v2 quotes agree with the v1 native oracle";
  let leb n =
    let b = Buffer.create 8 in
    let rec go n = let lo = Z.to_int (Z.logand n (z 127)) and hi = Z.shift_right n 7 in
      if Z.equal hi Z.zero then Buffer.add_char b (Char.chr lo) else (Buffer.add_char b (Char.chr (lo lor 128)); go hi) in
    go n; Buffer.contents b in
  let v1_bytes (o : order) = "\x02" ^ leb o.customer ^ leb o.discount_pct ^ leb (z (List.length o.lines)) ^ String.concat "" (List.map (fun l -> leb l.sku ^ leb l.qty ^ leb l.unit_price) o.lines) in
  let n_sem = 20_000 and bad = ref 0 in
  for i = 1 to n_sem do
    let o = { customer = z i; discount_pct = z (Random.int 110); lines = List.init (Random.int 8) (fun j -> { sku = z (if Random.int 30 = 0 then 0 else j); qty = z (Random.int 5); unit_price = rz () }) } in
    let v1 = Bytes.to_string (Native_core.handle (Bytes.of_string (v1_bytes o))) in
    let v2_as_v1 = match call (PriceOrder o) with
      | Ok (Quote q) -> "\x00" ^ leb q.subtotal ^ leb q.discount ^ leb q.total ^ leb q.line_count
      | Error (Order e) -> Printf.sprintf "\x01%c" (Char.chr (match e with NoLines -> 16 | ZeroQty -> 17 | BadDiscount -> 18 | DuplicateSku -> 19))
      | r -> "unexpected " ^ pp r in
    if v1 <> v2_as_v1 then (incr bad; if !bad < 5 then fail "v1/v2 disagree on order %d" i)
  done;
  Printf.printf "semantics: %d random orders, %d disagreements\n" n_sem !bad;

  print_endline "-- decoder agreement fuzz (generated OCaml decoder vs Lean decoder, random bytes)";
  let n_fuzz = 200_000 and bad = ref 0 and accepted = ref 0 in
  let code_of = function Truncated -> 4 | Trailing -> 5 | BadTag -> 6 | _ -> -1 in
  for i = 1 to n_fuzz do
    let bs = Bytes.init (Random.int 24) (fun j -> if j = 0 && i mod 2 = 0 then Char.chr (Random.int 4) else Char.chr (Random.int 256)) in
    let reply = Leancore.call_api bs in
    match decode_reply reply with
    | Error c -> incr bad; if !bad < 5 then fail "reply does not decode (code %d) for %s" c (hex bs)
    | Ok lean ->
      (match decode_request bs, lean with
       | Ok r, _ -> incr accepted; if call r <> lean then (incr bad; if !bad < 5 then fail "accepted %s but replies differ" (hex bs))
       | Error c, Error (Transport e) when code_of e = c -> ()
       | Error c, got -> incr bad; if !bad < 5 then fail "OCaml rejects %s (code %d), Lean says %s" (hex bs) c (pp got))
  done;
  Printf.printf "fuzz: %d inputs (%d decodable requests), %d disagreements\n" n_fuzz !accepted !bad;
  print_endline "-- mutation fuzz (valid encodings, then 1-3 byte flips/truncations/insertions)";
  let mutate b =
    let s = Bytes.to_string b and len = Bytes.length b in
    match Random.int 4 with
    | 0 when len > 0 -> let b = Bytes.copy b in Bytes.set b (Random.int len) (Char.chr (Random.int 256)); Bytes.to_string b
    | 1 when len > 0 -> String.sub s 0 (Random.int len)
    | 2 -> s ^ String.make 1 (Char.chr (Random.int 256))
    | _ -> let i = Random.int (len + 1) in String.sub s 0 i ^ String.make 1 (Char.chr (Random.int 256)) ^ String.sub s i (len - i) in
  let n_mut = 100_000 and bad = ref 0 and accepted = ref 0 in
  for _ = 1 to n_mut do
    let r = match Random.int 3 with 0 -> Request_gate1 (rz ()) | 1 -> PriceOrder (ro ()) | _ -> Echo (ro ()) in
    let s = ref (Bytes.to_string (encode_request r)) in
    for _ = 1 to 1 + Random.int 3 do s := mutate (Bytes.of_string !s) done;
    let bs = Bytes.of_string !s in
    match decode_reply (Leancore.call_api bs) with
    | Error c -> incr bad; if !bad < 5 then fail "reply does not decode (code %d)" c
    | Ok lean ->
      (match decode_request bs, lean with
       | Ok r, _ -> incr accepted; if call r <> lean then (incr bad; if !bad < 5 then fail "mutation accepted but replies differ")
       | Error c, Error (Transport e) when code_of e = c -> ()
       | Error c, got -> incr bad; if !bad < 5 then fail "OCaml rejects (code %d), Lean says %s" c (pp got))
  done;
  Printf.printf "mutation fuzz: %d inputs (%d still decodable), %d disagreements\n" n_mut !accepted !bad;
  if !failures > 0 then (Printf.printf "%d FAILURES\n" !failures; exit 1) else print_endline "== generated client tests PASSED =="
